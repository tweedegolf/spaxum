#!/usr/bin/env bash
#
# Update the esbuild release that Spaxum pins.
#
# Spaxum does not ship esbuild itself: at build time it downloads the
# @esbuild/<platform> package for the host from the npm registry and verifies
# it against a pinned SHA-256 checksum. This script resolves an esbuild
# version, computes the checksums for all supported platforms and regenerates
# spaxum/src/esbuild_release.rs.
#
# Usage:
#   scripts/update-esbuild.sh [version]
#
#   version   Optional exact esbuild version (e.g. 0.28.1). Defaults to latest.
#
set -euo pipefail

# Supported platforms, named after the @esbuild/<platform> npm packages.
# Keep in sync with esbuild_platform() in spaxum/src/lib.rs.
PLATFORMS=(linux-x64 linux-arm64 darwin-x64 darwin-arm64)

REGISTRY="https://registry.npmjs.org"
DEST="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/spaxum/src/esbuild_release.rs"

for cmd in curl grep; do
  if ! command -v "$cmd" >/dev/null 2>&1; then
    echo "error: required command '$cmd' not found" >&2
    exit 1
  fi
done

if command -v sha256sum >/dev/null 2>&1; then
  sha256() { sha256sum "$1" | cut -d' ' -f1; }
elif command -v shasum >/dev/null 2>&1; then
  sha256() { shasum -a 256 "$1" | cut -d' ' -f1; }
else
  echo "error: neither 'sha256sum' nor 'shasum' found" >&2
  exit 1
fi

# Resolve the target version (either a pinned version or the latest dist-tag).
REQUESTED="${1:-latest}"
echo "Resolving esbuild@${REQUESTED}..."
VERSION="$(curl -fsSL "${REGISTRY}/esbuild/${REQUESTED}" | grep -o '"version":"[^"]*"' | head -n1 | cut -d'"' -f4)"

if [ -z "$VERSION" ]; then
  echo "error: could not resolve esbuild version from registry" >&2
  exit 1
fi

CURRENT="$(grep -o 'ESBUILD_VERSION: &str = "[^"]*"' "$DEST" 2>/dev/null | cut -d'"' -f2 || true)"
echo "Current: ${CURRENT:-none}"
echo "Target:  ${VERSION}"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# Compute all checksums first, so a failure leaves the pinned release untouched.
{
  echo "// Generated by scripts/update-esbuild.sh, do not edit by hand."
  echo
  echo "/// Version of esbuild that is downloaded at build time"
  echo "pub(crate) const ESBUILD_VERSION: &str = \"${VERSION}\";"
  echo
  echo "/// SHA-256 checksums of the \`@esbuild/<platform>\` npm tarballs for this version"
  echo "pub(crate) const ESBUILD_CHECKSUMS: &[(&str, &str)] = &["
} > "$TMP/release.rs"

for platform in "${PLATFORMS[@]}"; do
  TARBALL="${REGISTRY}/@esbuild/${platform}/-/${platform}-${VERSION}.tgz"
  echo "Downloading ${TARBALL}..." >&2
  curl -fsSL "$TARBALL" -o "$TMP/$platform.tgz"
  cat >> "$TMP/release.rs" <<EOF
    (
        "${platform}",
        "$(sha256 "$TMP/$platform.tgz")",
    ),
EOF
done

echo "];" >> "$TMP/release.rs"

mv "$TMP/release.rs" "$DEST"

echo "Pinned esbuild ${VERSION} for: ${PLATFORMS[*]}"
